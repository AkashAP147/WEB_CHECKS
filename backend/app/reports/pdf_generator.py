from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    HRFlowable,
    Image,
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)
from reportlab.pdfgen import canvas
from backend.app.config import settings
from backend.app.screenshots.capture import generate_diagnostic_screenshot


class FastAuditCanvas(canvas.Canvas):
    """High-speed 1-pass canvas that decorates pages without memory buffering."""

    def showPage(self):
        if self._pageNumber > 1:
            self.saveState()
            self.setFont("Helvetica", 9)
            self.setFillColor(colors.HexColor("#64748b"))
            self.drawString(54, letter[1] - 36, "WebPulse — Website Health & DNS Audit Report")
            self.setStrokeColor(colors.HexColor("#e2e8f0"))
            self.setLineWidth(0.5)
            self.line(54, letter[1] - 42, letter[0] - 54, letter[1] - 42)
            self.line(54, 46, letter[0] - 54, 46)
            self.drawString(54, 32, "Confidential — Generated by WebPulse Platform")
            self.drawRightString(letter[0] - 54, 32, f"Page {self._pageNumber}")
            self.restoreState()
        super().showPage()


class PDFReportGenerator:
    """Generates professional PDF audit reports."""

    def __init__(self):
        self.styles = getSampleStyleSheet()
        self._setup_custom_styles()

    def _setup_custom_styles(self):
        self.title_style = ParagraphStyle(
            "CoverTitle",
            parent=self.styles["Title"],
            fontName="Helvetica-Bold",
            fontSize=32,
            leading=38,
            textColor=colors.HexColor("#0f172a"),
            alignment=0,
            spaceAfter=8,
        )
        self.subtitle_style = ParagraphStyle(
            "CoverSubtitle",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=16,
            leading=22,
            textColor=colors.HexColor("#475569"),
            spaceAfter=24,
        )
        self.meta_style = ParagraphStyle(
            "CoverMeta",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=11,
            leading=16,
            textColor=colors.HexColor("#334155"),
        )
        self.h1_style = ParagraphStyle(
            "Heading1_Custom",
            parent=self.styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=18,
            leading=22,
            textColor=colors.HexColor("#0f172a"),
            spaceBefore=16,
            spaceAfter=12,
        )
        self.h2_style = ParagraphStyle(
            "Heading2_Custom",
            parent=self.styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#1e293b"),
            spaceBefore=10,
            spaceAfter=6,
        )
        self.body_style = ParagraphStyle(
            "Body_Custom",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13,
            textColor=colors.HexColor("#1e293b"),
        )
        self.code_style = ParagraphStyle(
            "Code_Custom",
            parent=self.styles["Normal"],
            fontName="Courier",
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#0f172a"),
        )

    async def generate(
        self,
        scan: Dict[str, Any],
        results: List[Dict[str, Any]],
        output_path: str,
        status_filter: Optional[str] = None,
        report_mode: Optional[str] = None,
    ) -> str:
        """Create the PDF report and write to output_path with status sorting & filtering.
        
        report_mode:
            'summary': Fast high-density table without heavy per-page screenshots (recommended for > 50 targets).
            'issues': Visual diagnostic screenshots for offline and error targets only.
            'visual': Full visual inspection report including screenshots.
            None: Auto-select ('summary' for > 50 targets, 'visual' for <= 50 targets).
        """
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)

        # 1. Apply status filtering if requested (ONLINE, OFFLINE, ERRORS)
        filtered_results = list(results)
        if status_filter:
            sf = status_filter.strip().upper()
            if sf == "ONLINE":
                filtered_results = [r for r in filtered_results if str(r.get("status") or "").upper() == "ONLINE"]
            elif sf == "OFFLINE":
                filtered_results = [r for r in filtered_results if str(r.get("status") or "").upper() == "OFFLINE"]
            elif sf in ("ERRORS", "ERROR", "WARNINGS"):
                filtered_results = [
                    r for r in filtered_results if str(r.get("status") or "").upper() not in ("ONLINE", "OFFLINE")
                ]

        # 2. Sort results: ONLINE first -> OFFLINE second -> ERRORS & WARNINGS third
        def _get_sort_key(r: Dict[str, Any]):
            st = str(r.get("status") or "").upper()
            rank = 1 if st == "ONLINE" else (2 if st == "OFFLINE" else 3)
            domain_key = str(r.get("domain") or r.get("original_url") or "").lower()
            return (rank, domain_key)

        results = sorted(filtered_results, key=_get_sort_key)

        # Determine whether to include individual visual screenshot pages
        if report_mode == "summary":
            include_visuals = False
        elif report_mode == "visual":
            include_visuals = True
        elif report_mode == "issues":
            include_visuals = True
        elif status_filter in ("OFFLINE", "ERRORS", "ERROR", "WARNINGS"):
            include_visuals = True
        else:
            include_visuals = len(results) <= 50

        doc = SimpleDocTemplate(
            output_path,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        story = []

        # Helper for date display
        def _format_pdf_dt(dt_val: Any) -> str:
            if not dt_val:
                return datetime.now(timezone.utc).strftime("%b %d, %Y, %I:%M %p UTC")
            try:
                s = str(dt_val).strip()
                clean = s.replace("Z", "").replace("T", " ")
                if "." in clean:
                    clean = clean.split(".")[0]
                dt = datetime.fromisoformat(clean)
                return dt.strftime("%b %d, %Y, %I:%M:%S %p UTC")
            except Exception:
                return str(dt_val)

        # =====================================================================
        # 1. COVER PAGE
        # =====================================================================
        story.append(Spacer(1, 40))

        # Brand pill / header
        brand_table = Table(
            [[
                Paragraph(
                    "<font color='#4f46e5'><b>WEBPULSE</b></font> &nbsp;|&nbsp; "
                    "<font color='#64748b'>Enterprise Website Health & DNS Audit</font>",
                    self.body_style,
                )
            ]],
            colWidths=[504],
        )
        brand_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5f9")),
                ("PADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
            ])
        )
        story.append(brand_table)
        story.append(Spacer(1, 40))

        # Big Title & Subtitle
        scope_title = "Website Health &amp; DNS Audit Report"
        if status_filter:
            scope_title += f" &mdash; <font color='#4f46e5'>{status_filter.upper()} Targets Only</font>"

        story.append(Paragraph(scope_title, self.title_style))
        story.append(
            Paragraph(
                "Automated verification of availability, DNS configuration, SSL certificates, "
                "and visual rendering. Targets sorted by status (Online &rarr; Offline &rarr; Errors).",
                self.subtitle_style,
            )
        )

        story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#4f46e5"), spaceBefore=10, spaceAfter=30))

        # Scan Metadata block
        scan_id = scan.get("id", "N/A")
        created_at_raw = scan.get("created_at")
        formatted_date = _format_pdf_dt(created_at_raw)
        total_urls = len(results)
        uploaded_filename = scan.get("filename")
        source_label = uploaded_filename if uploaded_filename else "Direct URL Submission"

        meta_data = [
            [Paragraph("<b>Audit ID:</b>", self.body_style), Paragraph(str(scan_id), self.code_style)],
            [Paragraph("<b>Source / Uploaded File:</b>", self.body_style), Paragraph(f"<b>{source_label}</b>", self.body_style)],
            [Paragraph("<b>Audit Timestamp:</b>", self.body_style), Paragraph(formatted_date, self.body_style)],
            [Paragraph("<b>Report Scope:</b>", self.body_style), Paragraph(f"<b>{status_filter.upper() if status_filter else 'ALL (Sorted)'}</b>", self.body_style)],
            [Paragraph("<b>Total Targets in Report:</b>", self.body_style), Paragraph(str(total_urls), self.body_style)],
            [Paragraph("<b>Audit Engine:</b>", self.body_style), Paragraph("WebPulse Core v1.0 (dnspython, HTTPX, Playwright)", self.body_style)],
        ]
        meta_table = Table(meta_data, colWidths=[160, 344])
        meta_table.setStyle(
            TableStyle([
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("LINEBELOW", (0, 0), (-1, -1), 0.5, colors.HexColor("#f1f5f9")),
            ])
        )
        story.append(meta_table)

        story.append(Spacer(1, 100))
        disclaimer = Paragraph(
            "<font color='#64748b' size='8'>This report contains automated security, DNS, and availability diagnostics. "
            "Scan data reflects the exact state of target endpoints at the time of execution.</font>",
            self.body_style,
        )
        story.append(disclaimer)

        story.append(PageBreak())

        # =====================================================================
        # 2. EXECUTIVE SUMMARY
        # =====================================================================
        story.append(Paragraph("Executive Summary", self.h1_style))
        story.append(
            Paragraph(
                f"Aggregated health indicators across all submitted web assets from <b>{source_label}</b>.",
                self.body_style,
            )
        )
        story.append(Spacer(1, 15))

        # Compute summary metrics
        online_cnt = sum(1 for r in results if r.get("status") == "ONLINE")
        offline_cnt = sum(1 for r in results if r.get("status") == "OFFLINE")
        dns_err_cnt = sum(1 for r in results if r.get("status") == "DNS_ERROR")
        ssl_err_cnt = sum(1 for r in results if r.get("status") == "SSL_ERROR")
        other_err_cnt = total_urls - (online_cnt + offline_cnt + dns_err_cnt + ssl_err_cnt)

        valid_times = [
            float(r["response_time_ms"])
            for r in results
            if r.get("response_time_ms") is not None
        ]
        avg_rt = f"{sum(valid_times)/len(valid_times):.1f} ms" if valid_times else "N/A"
        avail_pct = f"{(online_cnt / total_urls * 100):.1f}%" if total_urls else "0%"

        # KPI metric boxes
        summary_kpi_data = [
            [
                Paragraph(f"<font size='18'><b>{online_cnt}</b></font><br/><font color='#16a34a'>Online</font>", self.body_style),
                Paragraph(f"<font size='18'><b>{offline_cnt}</b></font><br/><font color='#dc2626'>Offline</font>", self.body_style),
                Paragraph(f"<font size='18'><b>{dns_err_cnt}</b></font><br/><font color='#d97706'>DNS Errors</font>", self.body_style),
                Paragraph(f"<font size='18'><b>{ssl_err_cnt}</b></font><br/><font color='#dc2626'>SSL Issues</font>", self.body_style),
                Paragraph(f"<font size='18'><b>{avail_pct}</b></font><br/><font color='#2563eb'>Availability</font>", self.body_style),
                Paragraph(f"<font size='14'><b>{avg_rt}</b></font><br/><font color='#475569'>Avg Response</font>", self.body_style),
            ]
        ]
        kpi_table = Table(summary_kpi_data, colWidths=[84, 84, 84, 84, 84, 84])
        kpi_table.setStyle(
            TableStyle([
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#e2e8f0")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 10),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
            ])
        )
        story.append(kpi_table)
        story.append(Spacer(1, 20))

        # =====================================================================
        # 2. STATUS DIRECTORY TABLE (High-performance chunking, for Summary mode)
        # =====================================================================
        if not include_visuals:
            story.append(Paragraph("Website Status Overview &amp; Audit Directory", self.h2_style))
            header_cells = [
                Paragraph("<b>Domain / Target URL</b>", self.body_style),
                Paragraph("<b>Status</b>", self.body_style),
                Paragraph("<b>HTTP Code</b>", self.body_style),
                Paragraph("<b>Latency</b>", self.body_style),
                Paragraph("<b>SSL</b>", self.body_style),
                Paragraph("<b>DNS</b>", self.body_style),
            ]

            data_rows = []
            for r in results:
                domain = r.get("domain") or r.get("original_url", "")
                orig_url = r.get("original_url", "")
                final_url = r.get("final_url") or orig_url
                status = r.get("status", "UNKNOWN")
                http_code = str(r.get("http_status_code") or "—")
                rt = f"{r.get('response_time_ms'):.0f}ms" if r.get("response_time_ms") else "—"

                status_color = "#16a34a" if status == "ONLINE" else "#dc2626" if status == "OFFLINE" else "#d97706"
                status_cell = Paragraph(f"<font color='{status_color}'><b>{status}</b></font>", self.body_style)
                ssl_cell = Paragraph("<font color='#16a34a'>PASS</font>" if status not in ("SSL_ERROR", "OFFLINE") else "<font color='#dc2626'>ISSUE</font>", self.body_style)
                dns_cell = Paragraph("<font color='#16a34a'>RESOLVED</font>" if status != "DNS_ERROR" else "<font color='#dc2626'>FAILED</font>", self.body_style)

                if final_url and orig_url and final_url.rstrip('/') != orig_url.rstrip('/'):
                    domain_para = Paragraph(f"<font size='8'><b>{domain}</b><br/><font color='#2563eb'>&rarr; {final_url[:40]}</font></font>", self.body_style)
                else:
                    domain_para = Paragraph(f"<font size='8.5'>{domain}</font>", self.body_style)

                data_rows.append([
                    domain_para,
                    status_cell,
                    Paragraph(http_code, self.body_style),
                    Paragraph(rt, self.body_style),
                    ssl_cell,
                    dns_cell,
                ])

            TABLE_CHUNK_SIZE = 35
            for chunk_idx in range(0, max(len(data_rows), 1), TABLE_CHUNK_SIZE):
                chunk_rows = [header_cells] + data_rows[chunk_idx:chunk_idx + TABLE_CHUNK_SIZE]
                t = Table(chunk_rows, colWidths=[184, 80, 60, 60, 60, 60])
                t.setStyle(
                    TableStyle([
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
                    ])
                )
                story.append(t)
                story.append(Spacer(1, 8))

        # =====================================================================
        # 3. DETAILED VISUAL INSPECTION APPENDIX (Full 1,000 targets per batch with images)
        # =====================================================================
        if include_visuals:
            story.append(PageBreak())
            story.append(Paragraph("Visual Inspection &amp; Diagnostic Snapshots", self.h1_style))
            story.append(
                Paragraph(
                    "High-fidelity rendered snapshots of target endpoints. "
                    "Offline and warning sites display automated server handshake diagnostics.",
                    self.subtitle_style,
                )
            )
            story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#4f46e5"), spaceBefore=4, spaceAfter=20))

            visual_results = results
            for idx, r in enumerate(visual_results, start=1):
                domain = r.get("domain") or r.get("original_url", f"Site #{idx}")
                orig_url = r.get("original_url", "")
                final_url = r.get("final_url") or orig_url
                status = r.get("status", "UNKNOWN")
                http_code = str(r.get("http_status_code") or "—")
                resp_time = f"{r.get('response_time_ms'):.1f} ms" if r.get("response_time_ms") else "—"
                server_info = r.get("server_info") or "Not disclosed"
                title = r.get("website_title") or "—"
                error_msg = r.get("error_message") or "None"
                screenshot_path = r.get("screenshot_path")

                status_color = "#16a34a" if status == "ONLINE" else "#dc2626" if status == "OFFLINE" else "#d97706"

                website_elements = []

                # Website Header Bar
                website_elements.append(
                    Paragraph(
                        f"#{idx} &nbsp; <b>{domain}</b> &nbsp;&nbsp; "
                        f"<font color='{status_color}'>[{status}]</font>",
                        self.h1_style,
                    )
                )
                website_elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceBefore=2, spaceAfter=10))

                # Details Key-Value Table
                is_redirected = final_url and orig_url and final_url.rstrip('/') != orig_url.rstrip('/')
                final_url_para = Paragraph(f"<font color='#2563eb'><b>{final_url}</b> [Redirected]</font>", self.code_style) if is_redirected else Paragraph(final_url, self.code_style)

                site_details = [
                    [Paragraph("<b>Original Target:</b>", self.body_style), Paragraph(orig_url, self.code_style)],
                    [Paragraph("<b>Final URL:</b>", self.body_style), final_url_para],
                    [Paragraph("<b>HTTP Status:</b>", self.body_style), Paragraph(http_code, self.body_style)],
                    [Paragraph("<b>Response Time:</b>", self.body_style), Paragraph(resp_time, self.body_style)],
                    [Paragraph("<b>Page Title:</b>", self.body_style), Paragraph(title, self.body_style)],
                    [Paragraph("<b>Web Server:</b>", self.body_style), Paragraph(server_info, self.body_style)],
                ]

                if error_msg != "None":
                    site_details.append([
                        Paragraph("<b>Diagnostic Error:</b>", self.body_style),
                        Paragraph(f"<font color='#dc2626'>{error_msg}</font>", self.body_style),
                    ])

                details_table = Table(site_details, colWidths=[120, 384])
                details_table.setStyle(
                    TableStyle([
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                        ("LINEBELOW", (0, 0), (-1, -1), 0.5, colors.HexColor("#f1f5f9")),
                    ])
                )
                website_elements.append(details_table)
                website_elements.append(Spacer(1, 14))

                # Screenshot section (guaranteed visual rendering)
                website_elements.append(Paragraph("Visual Inspection &amp; Page Rendering", self.h2_style))

                img_added = False
                full_img_path = None
                if screenshot_path:
                    candidates = [
                        screenshot_path,
                        os.path.join(settings.screenshots_dir, os.path.basename(screenshot_path)),
                        os.path.join(settings.project_root, "storage", screenshot_path),
                        os.path.join(settings.project_root, screenshot_path),
                        os.path.join("storage", screenshot_path),
                        os.path.join(".", screenshot_path),
                    ]
                    for cand in candidates:
                        if os.path.isfile(cand) and os.path.getsize(cand) > 0:
                            full_img_path = cand
                            break

                # If no screenshot was on disk, generate a crisp diagnostic snapshot card on the fly
                if not full_img_path or not os.path.isfile(full_img_path):
                    gen_filename = f"diag_{scan_id}_{idx}_{int(time.time())}.png"
                    temp_diag_path = os.path.join(settings.screenshots_dir, gen_filename)
                    status_dict = {
                        "status": status,
                        "http_status_code": r.get("http_status_code"),
                        "response_time_ms": r.get("response_time_ms"),
                        "domain": domain,
                        "error_message": error_msg,
                    }
                    if generate_diagnostic_screenshot(temp_diag_path, orig_url or domain, status_dict):
                        full_img_path = temp_diag_path

                if full_img_path and os.path.isfile(full_img_path):
                    try:
                        # Compress / optimize image with PIL thumbnail to reduce memory & PDF size by 85%
                        optimized_path = full_img_path
                        try:
                            from PIL import Image as PILImage
                            thumb_path = full_img_path + ".thumb.jpg"
                            if not os.path.isfile(thumb_path):
                                with PILImage.open(full_img_path) as im:
                                    rgb_im = im.convert("RGB")
                                    rgb_im.thumbnail((640, 400))
                                    rgb_im.save(thumb_path, "JPEG", quality=70, optimize=True)
                            if os.path.isfile(thumb_path):
                                optimized_path = thumb_path
                        except Exception:
                            pass

                        img = Image(optimized_path, width=480, height=270)
                        website_elements.append(img)
                        img_added = True
                    except Exception as img_err:
                        website_elements.append(
                            Paragraph(f"<font color='#dc2626'>Unable to render screenshot: {img_err}</font>", self.body_style)
                        )

                if not img_added:
                    placeholder = Table(
                        [[Paragraph("<font color='#64748b'>Visual snapshot unavailable</font>", self.body_style)]],
                        colWidths=[500],
                        rowHeights=[60],
                    )
                    placeholder.setStyle(
                        TableStyle([
                            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#e2e8f0")),
                            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                        ])
                    )
                    website_elements.append(placeholder)

                story.append(KeepTogether(website_elements[:4]))
                story.extend(website_elements[4:])
                if idx < len(visual_results):
                    story.append(PageBreak())

        # Build document with fast 1-pass canvas
        doc.build(story, canvasmaker=FastAuditCanvas)
        return output_path
